public class Java7 {
    public static void main(String[] args) {
        int x = 3;
        switch (x) {
            case 1:
                System.out.println("Bangladesh");
                break;
            case 2:
                System.out.println("London");
                break;
            case 3:
                System.out.println("Edinburgh");
                break;
            default:
                System.out.println("Out of the World!");
        }
}
}