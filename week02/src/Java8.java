public class Java8 {
    public static void main(String[] args) {
        int x;
        x = 20;

        System.out.println("Current value of x is: " + x++);
        System.out.println("Current value of x is: " + ++x);

        x = 20;
        System.out.println("Current value of x is: " + x--);
        System.out.println("Current value of x is: " + --x);



    }
}